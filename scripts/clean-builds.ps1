[CmdletBinding(SupportsShouldProcess)]
param()
$ErrorActionPreference = 'Stop'
$workspaceRoot = [IO.Path]::GetFullPath((Split-Path $PSScriptRoot -Parent))
$candidates = @('target','dist','out','.mpv-cache','.npm-cache','.builder-cache','.cache','.electron-cache','dist-bulk','src-tauri/gen','src-tauri/permissions/autogenerated')
$removedBytes = [long]0
foreach ($relative in $candidates) {
    $candidate = [IO.Path]::GetFullPath((Join-Path $workspaceRoot $relative))
    if (-not $candidate.StartsWith($workspaceRoot + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) { throw "Refusing a target outside the workspace: $candidate" }
    if (-not (Test-Path -LiteralPath $candidate)) { continue }
    $item = Get-Item -LiteralPath $candidate -Force
    if ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw "Refusing to recurse into a linked directory: $candidate" }
    $bytes = (Get-ChildItem -LiteralPath $candidate -Recurse -File -Force | Measure-Object -Property Length -Sum).Sum
    if ($PSCmdlet.ShouldProcess($candidate, 'Remove generated build output/cache')) {
        Remove-Item -LiteralPath $candidate -Recurse -Force
        $removedBytes += $bytes
    }
}
Write-Output ('Removed {0:N2} GiB of generated output. Source, dependencies, vendor/mpv, release files, and app data were preserved.' -f ($removedBytes / 1GB))
